#include <stdint.h>
#include <lk/reg.h>
#include <platform/bcm28xx/arm.h>
#include <platform/bcm28xx/arm_chainloader.h>
#include <platform/bcm28xx/power.h>
#include <platform/bcm28xx/udelay.h>

static const uint8_t bresp_sequence[] = {
  0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x1c, 0x18, 0x1c, 0x18, 0x00,
  0x10, 0x14, 0x10, 0x1c, 0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x00,
  0x10, 0x14, 0x10, 0x1c, 0x18, 0x1c, 0x10, 0x14, 0x18, 0x1c, 0x10, 0x14, 0x10, 0x00,
  0x10, 0x14, 0x18, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x00,
  0x10, 0x14, 0x18, 0x14, 0x18, 0x14, 0x10, 0x14, 0x10, 0x14, 0x10, 0x14, 0x18, 0x00,
};

void arm_chainloader_release_bridge(void) {
  *REG32(PM_PROC) |= PM_PASSWORD | (1u << 6);
  for (unsigned int i = 0; i < sizeof(bresp_sequence); ++i) {
    *REG32(ARM_CONTROL0) = (*REG32(ARM_CONTROL0) & ~(ARM_C0_BRESP1 | ARM_C0_BRESP2)) |
                           bresp_sequence[i];
    udelay(30);
  }
  *REG32(PM_PROC) |= PM_PASSWORD | (1u << 6);
  udelay(300);
  *REG32(ARM_CONTROL1) &= ~ARM_C1_REQSTOP;
  udelay(300);
  uint32_t pm_proc = *REG32(PM_PROC);
  *REG32(PM_PROC) = pm_proc | PM_PASSWORD | (1u << 6);
}
